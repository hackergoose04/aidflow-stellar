"""One-click Testnet setup for AidFlow.

Creates 5 accounts, funds them with Friendbot, issues the test asset AIDUSD,
and writes all keys to .env (TESTNET ONLY — still never commit .env).

  ISSUER        issues AIDUSD
  DISTRIBUTION  the NGO wallet that pays beneficiaries
  BEN1, BEN2    beneficiaries WITH an AIDUSD trustline  -> plain Payment
  BEN3          beneficiary WITHOUT a trustline          -> Claimable Balance

Usage:
  python scripts/testnet_setup.py           # reuse keys in .env if present
  python scripts/testnet_setup.py --reset   # new keys (use after a Testnet reset)
"""
from __future__ import annotations

import sys

from stellar_sdk import Asset, Keypair, TransactionBuilder

import stellar_common as sc

ACCOUNTS = ["ISSUER", "DISTRIBUTION", "BEN1", "BEN2", "BEN3"]
WITH_TRUSTLINE = ["DISTRIBUTION", "BEN1", "BEN2"]
INITIAL_SUPPLY = "10000"


def load_or_create_keys(reset: bool) -> dict[str, Keypair]:
    keys = {}
    for name in ACCOUNTS:
        secret = None if reset else sc.os.getenv(f"{name}_SECRET")
        keys[name] = Keypair.from_secret(secret) if secret else Keypair.random()
    return keys


def write_env(keys: dict[str, Keypair]) -> None:
    """Write the account keys, keeping every other entry already in .env
    (REGISTRY_CONTRACT_ID, REGISTRY_SECRET, PII_HMAC_SECRET, ...): losing an HMAC secret
    would orphan every hash made with it."""
    managed = {"HORIZON_URL": sc.HORIZON_URL, "RPC_URL": sc.RPC_URL, "ASSET_CODE": sc.ASSET_CODE}
    for name, kp in keys.items():
        managed[f"{name}_PUBLIC"] = kp.public_key
        managed[f"{name}_SECRET"] = kp.secret
    kept = []
    if sc.ENV_PATH.exists():
        for line in sc.ENV_PATH.read_text().splitlines():
            key = line.split("=", 1)[0]
            if line.startswith("#") or key in managed:
                continue
            kept.append(line)
    lines = ["# AidFlow TESTNET keys. Generated by scripts/testnet_setup.py. Do not commit."]
    lines += [f"{k}={v}" for k, v in managed.items()] + kept
    sc.ENV_PATH.write_text("\n".join(lines) + "\n")


def submit(builder_source: Keypair, build_ops) -> str:
    server = sc.horizon()
    account = server.load_account(builder_source.public_key)
    builder = TransactionBuilder(account, sc.NETWORK_PASSPHRASE, base_fee=sc.BASE_FEE)
    build_ops(builder)
    tx = builder.set_timeout(sc.TX_TIMEOUT_SECONDS).build()
    tx.sign(builder_source)
    server.submit_transaction(tx)
    return tx.hash_hex()


def main() -> None:
    reset = "--reset" in sys.argv
    keys = load_or_create_keys(reset)
    write_env(keys)
    asset = Asset(sc.ASSET_CODE, keys["ISSUER"].public_key)

    print("1/3 Funding accounts with Friendbot...")
    for name, kp in keys.items():
        sc.fund_with_friendbot(kp.public_key)
        print(f"  {name:13s} {kp.public_key}")

    print(f"2/3 Adding {sc.ASSET_CODE} trustlines (BEN3 intentionally skipped)...")
    for name in WITH_TRUSTLINE:
        kp = keys[name]
        balances = sc.horizon().accounts().account_id(kp.public_key).call()["balances"]
        if any(b.get("asset_code") == sc.ASSET_CODE for b in balances):
            print(f"  {name}: already trusts {sc.ASSET_CODE}")
            continue
        submit(kp, lambda b: b.append_change_trust_op(asset=asset))
        print(f"  {name}: trustline added")

    print(f"3/3 Issuing {INITIAL_SUPPLY} {sc.ASSET_CODE} to DISTRIBUTION...")
    tx_hash = submit(
        keys["ISSUER"],
        lambda b: b.append_payment_op(
            destination=keys["DISTRIBUTION"].public_key, asset=asset, amount=INITIAL_SUPPLY
        ),
    )
    print(f"  done: {sc.explorer_link(tx_hash)}")
    print(f"\nKeys saved to {sc.ENV_PATH}. Next: python scripts/spike_payment.py")


if __name__ == "__main__":
    main()
